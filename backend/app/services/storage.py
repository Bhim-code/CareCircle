"""Where uploaded files live. One small interface, so the place can change by settings.

Today: LocalStorage, a private folder on the server (STORAGE_DIR). It is never
served as a folder; files are only reachable through signed, expiring links that
the API hands to people allowed to see them.

Later: a cloud bucket (S3, Cloudflare R2, ...) is one new class with the same four
methods, chosen by STORAGE_BACKEND. Nothing else in the code changes.
"""

import re
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import get_settings

_SAFE_KEY = re.compile(r"^[a-z0-9/_.-]{1,200}$")


class Storage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...
    def read(self, key: str) -> bytes: ...
    def path(self, key: str) -> Path | None: ...  # a local path if there is one (for fast serving)
    def delete(self, key: str) -> None: ...


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _file(self, key: str) -> Path:
        # Keys are generated by the server, but check anyway: no "..", no absolute paths.
        if not _SAFE_KEY.match(key) or ".." in key:
            raise ValueError("bad storage key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ValueError("bad storage key")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._file(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".part")
        tmp.write_bytes(data)
        tmp.replace(path)  # appears all at once, never half-written

    def read(self, key: str) -> bytes:
        return self._file(key).read_bytes()

    def path(self, key: str) -> Path | None:
        path = self._file(key)
        return path if path.is_file() else None

    def delete(self, key: str) -> None:
        self._file(key).unlink(missing_ok=True)


@lru_cache
def get_storage() -> Storage:
    settings = get_settings()
    if settings.storage_backend == "local":
        return LocalStorage(settings.storage_dir)
    raise RuntimeError(f"Unknown STORAGE_BACKEND {settings.storage_backend!r}")
